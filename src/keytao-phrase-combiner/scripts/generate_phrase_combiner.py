#!/usr/bin/env python3
"""Generate the offline dictionary used by the KeyTao phrase combiner."""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from pathlib import Path

ENTRY_RE = re.compile(r"^([^#\t]+)\t([^\t\s]+)(?:\t([^\t\s]+))?")
IMPORT_RE = re.compile(r"^\s*-\s+([^\s#]+)\s*$")
CODE_RE = re.compile(r"^[a-z]+$")
CJK_RE = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]")


def dictionary_path(root: Path, name: str) -> Path:
    path = root / name
    if path.suffix == ".yaml":
        return path
    if path.name.endswith(".dict"):
        return path.with_suffix(".dict.yaml")
    return root / f"{name}.dict.yaml"


def load_dictionary(
    path: Path,
    words: dict[str, set[str]],
    weights: dict[str, int],
    visited: set[Path],
    generated_name: str,
) -> None:
    path = path.resolve()
    if path in visited or path.name == generated_name or not path.is_file():
        return
    visited.add(path)

    imports: list[str] = []
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        import_match = IMPORT_RE.match(raw_line)
        if import_match:
            imports.append(import_match.group(1))

        entry_match = ENTRY_RE.match(raw_line)
        if not entry_match:
            continue

        text, code, weight_text = entry_match.groups()
        if not CODE_RE.fullmatch(code):
            continue
        words[text].add(code)
        try:
            weight = int(weight_text or "0")
        except ValueError:
            weight = 0
        weights[text] = max(weights[text], weight)

    root = path.parent
    for imported in imports:
        load_dictionary(
            dictionary_path(root, imported),
            words,
            weights,
            visited,
            generated_name,
        )


def chinese_length(text: str) -> int:
    return len(CJK_RE.findall(text))


def code_variants(text: str, codes: set[str], min_code_length: int) -> set[str]:
    """Keep two code letters per Chinese character."""
    required_length = max(min_code_length, chinese_length(text) * 2)
    return {code[:required_length] for code in codes if len(code) >= required_length}


def generate_aliases(
    words: dict[str, set[str]],
    weights: dict[str, int],
    max_code_length: int,
    min_code_length: int,
) -> dict[str, dict[str, int]]:
    aliases: dict[str, dict[str, int]] = defaultdict(dict)

    for word in words:
        characters = list(word)
        if chinese_length(word) < 3:
            continue

        length = len(characters)
        segmentations: dict[int, tuple[int, set[str]]] = {length: (0, {""})}
        for position in range(length - 1, -1, -1):
            best_count = length + 1
            best_codes: set[str] = set()
            for end in range(position + 1, len(characters) + 1):
                if position == 0 and end == length:
                    continue
                segment = "".join(characters[position:end])
                variants = code_variants(
                    segment,
                    words.get(segment, set()),
                    min_code_length,
                )
                if not variants:
                    continue
                suffix_count, suffix_codes = segmentations[end]
                count = suffix_count + 1
                if not suffix_codes or count > best_count:
                    continue
                if count < best_count:
                    best_count = count
                    best_codes.clear()
                best_codes.update(code + suffix for code in variants for suffix in suffix_codes)
            segmentations[position] = (best_count, best_codes)

        for code in segmentations[0][1]:
            if max_code_length == 0 or len(code) <= max_code_length:
                aliases[code][word] = weights.get(word, 0)

    return aliases


def write_dictionary(path: Path, aliases: dict[str, dict[str, int]]) -> None:
    lines = [
        "# Rime dictionary",
        "# Generated by scripts/generate_phrase_combiner.py",
        "---",
        "name: phrase_combiner",
        'version: "1.0"',
        "sort: original",
        "import_tables:",
        "  - phrase_combiner.user",
        "columns:",
        "  - text",
        "  - code",
        "  - weight",
        "...",
        "",
    ]

    rows = [
        (text, code, weight)
        for code, entries in aliases.items()
        for text, weight in entries.items()
    ]
    rows.sort(key=lambda row: (row[0], row[1]))
    for text, code, weight in rows:
        lines.append(f"{text}\t{code}\t{weight}")

    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--source", default="../KeyTao/rime/keytao.extended.dict.yaml")
    parser.add_argument("--output", default="phrase_combiner.dict.yaml")
    parser.add_argument(
        "--max-code-length",
        type=int,
        default=0,
        help="Optional output limit; 0 means unlimited.",
    )
    parser.add_argument("--min-code-length", type=int, default=2)
    args = parser.parse_args()

    root = args.root.resolve()
    words: dict[str, set[str]] = defaultdict(set)
    weights: dict[str, int] = defaultdict(int)
    if not (root / args.source).is_file():
        parser.error(f"source dictionary not found: {root / args.source}")
    load_dictionary(root / args.source, words, weights, set(), Path(args.output).name)

    aliases = generate_aliases(
        words,
        weights,
        args.max_code_length,
        args.min_code_length,
    )
    write_dictionary(root / args.output, aliases)
    print(f"generated {sum(len(entries) for entries in aliases.values())} entries")


if __name__ == "__main__":
    main()
